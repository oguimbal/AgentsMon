    #[test]
    fn permission_records_retain_the_reviewer_when_the_context_leaves_the_tail() {
        let directory = tempfile::tempdir().unwrap();
        let path = directory.path().join("session.json");
        let transcript = directory.path().join("rollout.jsonl");
        let hook: HookInput = serde_json::from_str(
            r#"{"session_id":"s","hook_event_name":"PermissionRequest","tool_name":"Bash","tool_input":{"command":"private"}}"#,
        ).unwrap();
        let (state, activity) = event_state(&hook);
        let context =
            "{\"type\":\"turn_context\",\"payload\":{\"approvals_reviewer\":\"auto_review\"}}\n";
        fs::write(&transcript, context).unwrap();
        merge_record(
            &path,
            &hook,
            42,
            41,
            state,
            activity.clone(),
            extract_session_metadata(&transcript).unwrap(),
        )
        .unwrap();

        fs::write(
            &transcript,
            format!("{context}{}\n", "x".repeat(TRANSCRIPT_TAIL_BYTES as usize)),
        )
        .unwrap();
        let metadata = extract_session_metadata(&transcript).unwrap();
        assert_eq!(metadata.approvals_reviewer, None);
        merge_record(&path, &hook, 42, 41, state, activity.clone(), metadata).unwrap();
        let record = agentsmon_providers::CodexProvider::parse_file(&path).unwrap();
        assert_eq!(
            record.approvals_reviewer,
            Some(CodexApprovalsReviewer::AutoReview)
        );
        assert_eq!(record.activity, "Bash");
        assert!(!fs::read_to_string(&path).unwrap().contains("private"));

        // A new turn that omits the setting must not inherit an automatic reviewer.
        fs::write(&transcript, "{\"type\":\"turn_context\",\"payload\":{}}\n").unwrap();
        merge_record(
            &path,
            &hook,
            42,
            41,
            state,
            activity,
            extract_session_metadata(&transcript).unwrap(),
        )
        .unwrap();
        assert_eq!(
            agentsmon_providers::CodexProvider::parse_file(&path)
                .unwrap()
                .approvals_reviewer,
            None
        );
    }

