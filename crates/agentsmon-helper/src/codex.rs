const TRANSCRIPT_TAIL_BYTES: u64 = 512 * 1024;

#[derive(Debug, Deserialize)]
pub struct HookInput {
    pub session_id: String,
    #[serde(default)]
    pub transcript_path: Option<String>,
    #[serde(default)]
    pub cwd: String,
    pub hook_event_name: String,
    #[serde(default)]
    pub tool_name: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct CodexStatusRecord {
    session_id: String,
    pid: i32,
    ppid: i32,
    state: String,
    activity: String,
    timestamp: String,
    cwd: String,
    event: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    transcript_path: Option<String>,
    #[serde(skip_serializing_if = "Option::is_none")]
    context_used_percentage: Option<f32>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    rate_limits: Option<CodexRateLimits>,
    /// Thread name generated by Codex, read from its session index.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    title: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    approvals_reviewer: Option<CodexApprovalsReviewer>,
}

/// One line of `~/.codex/session_index.jsonl`; only the thread name is decoded.
#[derive(Debug, Deserialize)]
struct SessionIndexEntry {
    id: String,
    #[serde(default)]
    thread_name: Option<String>,
}

#[derive(Debug, Deserialize)]
struct TranscriptEnvelope {
    #[serde(rename = "type")]
    kind: String,
    payload: TranscriptMetadataPayload,
}

#[derive(Debug, Deserialize)]
struct TranscriptMetadataPayload {
    #[serde(rename = "type")]
    kind: Option<String>,
    info: Option<TokenCountInfo>,
    #[serde(default, alias = "rateLimits")]
    rate_limits: Option<CodexRateLimits>,
    approvals_reviewer: Option<CodexApprovalsReviewer>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct CodexRateLimits {
    #[serde(default)]
    primary: Option<CodexRateLimitWindow>,
    #[serde(default)]
    secondary: Option<CodexRateLimitWindow>,
    #[serde(default, alias = "planType")]
    plan_type: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
struct CodexRateLimitWindow {
    #[serde(alias = "usedPercent")]
    used_percent: f32,
    #[serde(default, alias = "windowDurationMins", alias = "windowMinutes")]
    window_minutes: Option<u64>,
    #[serde(default, alias = "resetsAt")]
    resets_at: Option<i64>,
}

#[derive(Default)]
struct SessionMetadata {
    context_percentage: Option<f32>,
    rate_limits: Option<CodexRateLimits>,
    title: Option<String>,
    // Outer None means no turn_context was visible in the bounded tail. An
    // observed context without a reviewer must clear the previous turn's value.
    approvals_reviewer: Option<Option<CodexApprovalsReviewer>>,
}

#[derive(Debug, Deserialize)]
struct TokenCountInfo {
    last_token_usage: Option<TokenUsage>,
    model_context_window: Option<u64>,
}

#[derive(Debug, Deserialize)]
struct TokenUsage {
    total_tokens: u64,
}

pub fn process(input: &[u8]) -> Result<()> {
    let hook: HookInput = serde_json::from_slice(input)?;
    validate_session_id(&hook.session_id)?;
    let path = runtime_root()?.join(format!("{}.json", hook.session_id));
    let (state, activity) = event_state(&hook);
    let mut metadata = hook
        .transcript_path
        .as_deref()
        .and_then(|path| extract_session_metadata(Path::new(path)).ok())
        .unwrap_or_default();
    metadata.title = session_index_path().and_then(|index| thread_name(&index, &hook.session_id));
    let (pid, ppid) = codex_process_ids();
    merge_record(&path, &hook, pid, ppid, state, activity, metadata)?;

    // Stop hooks require valid JSON on stdout. An empty object leaves Codex behavior unchanged.
    if hook.hook_event_name == "Stop" {
        println!("{{}}");
    }
    Ok(())
}

fn event_state(input: &HookInput) -> (&'static str, String) {
    match input.hook_event_name.as_str() {
        "SessionStart" => ("idle", String::new()),
        "PermissionRequest" => (
            "waiting",
            input.tool_name.clone().unwrap_or_else(|| "input".into()),
        ),
        // This tool blocks until the user answers. Async questions return
        // immediately and must retain the normal active tool state.
        "PreToolUse" if input.tool_name.as_deref() == Some("request_user_input") => {
            ("waiting", "request_user_input".into())
        }
        "PreCompact" => ("compacting", "compacting".into()),
        "Stop" => ("idle", String::new()),
        "PostCompact" | "UserPromptSubmit" | "PreToolUse" | "PostToolUse" => {
            ("active", input.tool_name.clone().unwrap_or_default())
        }
        _ => ("active", String::new()),
    }
}

fn runtime_root() -> Result<PathBuf> {
    let dirs = agentsmon_providers::app_dirs::project_dirs()
        .context("cannot resolve AgentsMon data directory")?;
    Ok(dirs.data_dir().join("codex"))
}

fn session_index_path() -> Option<PathBuf> {
    directories::UserDirs::new().map(|dirs| dirs.home_dir().join(".codex/session_index.jsonl"))
}

/// Codex appends an index line whenever it names (or renames) a thread; the
/// last entry for the session is current. Other lines are never decoded.
fn thread_name(index: &Path, session_id: &str) -> Option<String> {
    let content = fs::read_to_string(index).ok()?;
    content
        .lines()
        .filter(|line| line.contains(session_id))
        .filter_map(|line| serde_json::from_str::<SessionIndexEntry>(line).ok())
        .filter(|entry| entry.id == session_id)
        .filter_map(|entry| entry.thread_name)
        .map(|name| name.trim().to_owned())
        .rfind(|name| !name.is_empty())
}

fn validate_session_id(session_id: &str) -> Result<()> {
    if session_id.is_empty()
        || !session_id
            .chars()
            .all(|character| character.is_ascii_alphanumeric() || matches!(character, '-' | '_'))
    {
        bail!("invalid Codex session id");
    }
    Ok(())
}

fn merge_record(
    path: &Path,
    hook: &HookInput,
    pid: i32,
    ppid: i32,
    state: &str,
    activity: String,
    mut metadata: SessionMetadata,
) -> Result<()> {
    let parent = path.parent().context("Codex status path has no parent")?;
    fs::create_dir_all(parent)?;
    let lock = OpenOptions::new()
        .create(true)
        .read(true)
        .write(true)
        .truncate(false)
        .open(path.with_extension("lock"))?;
    lock.lock_exclusive()?;

    let previous = fs::read(path)
        .ok()
        .and_then(|bytes| serde_json::from_slice::<CodexStatusRecord>(&bytes).ok());
    if hook.hook_event_name == "PermissionRequest" && metadata.approvals_reviewer.is_none() {
        // A long turn (including one already open during an upgrade) can push
        // turn_context out of the tail. Resolve the actual current reviewer at
        // permission time instead of relying on missing or older cached settings.
        metadata.approvals_reviewer = hook
            .transcript_path
            .as_deref()
            .or_else(|| previous.as_ref()?.transcript_path.as_deref())
            .and_then(|path| latest_approvals_reviewer(Path::new(path)).ok().flatten());
    }
    let record = CodexStatusRecord {
        session_id: hook.session_id.clone(),
        pid: (pid > 0)
            .then_some(pid)
            .or_else(|| previous.as_ref().map(|record| record.pid))
            .unwrap_or_default(),
        ppid: (ppid > 0)
            .then_some(ppid)
            .or_else(|| previous.as_ref().map(|record| record.ppid))
            .unwrap_or_default(),
        state: state.into(),
        activity,
        timestamp: Utc::now().to_rfc3339(),
        cwd: if hook.cwd.is_empty() {
            previous
                .as_ref()
                .map(|record| record.cwd.clone())
                .unwrap_or_default()
        } else {
            hook.cwd.clone()
        },
        event: hook.hook_event_name.clone(),
        transcript_path: hook.transcript_path.clone().or_else(|| {
            previous
                .as_ref()
                .and_then(|record| record.transcript_path.clone())
        }),
        context_used_percentage: merged_context_percentage(
            hook.hook_event_name.as_str(),
            metadata.context_percentage,
            previous
                .as_ref()
                .and_then(|record| record.context_used_percentage),
        ),
        rate_limits: metadata.rate_limits.or_else(|| {
            previous
                .as_ref()
                .and_then(|record| record.rate_limits.clone())
        }),
        title: metadata
            .title
            .or_else(|| previous.as_ref().and_then(|record| record.title.clone())),
        approvals_reviewer: metadata.approvals_reviewer.unwrap_or_else(|| {
            previous
                .as_ref()
                .and_then(|record| record.approvals_reviewer)
        }),
    };

    let temporary = path.with_extension(format!("tmp.{}", std::process::id()));
    let mut file = File::create(&temporary)?;
    serde_json::to_writer(&mut file, &record)?;
    file.sync_all()?;
    crate::record::replace_atomically(&temporary, path)?;
    FileExt::unlock(&lock)?;
    Ok(())
}

fn merged_context_percentage(
    event: &str,
    current: Option<f32>,
    previous: Option<f32>,
) -> Option<f32> {
    if event == "PostCompact" {
        current
    } else {
        current.or(previous)
    }
}

fn extract_session_metadata(path: &Path) -> Result<SessionMetadata> {
    let mut file = File::open(path)?;
    let length = file.metadata()?.len();
    let start = length.saturating_sub(TRANSCRIPT_TAIL_BYTES);
    file.seek(SeekFrom::Start(start))?;
    let mut tail = Vec::new();
    file.take(length - start).read_to_end(&mut tail)?;

    let mut lines = tail.split(|byte| *byte == b'\n');
    if start > 0 {
        let _ = lines.next();
    }
    // Do not use a record until Codex has finished writing its newline.
    let _ = lines.next_back();
    let mut metadata = SessionMetadata::default();
    let mut found_usage = false;
    for line in lines.rev() {
        let is_usage = !found_usage
            && contains(line, br#""type":"event_msg""#)
            && contains(line, br#""type":"token_count""#);
        let is_context =
            metadata.approvals_reviewer.is_none() && contains(line, br#""type":"turn_context""#);
        if !is_usage && !is_context {
            continue;
        }
        let Ok(envelope) = serde_json::from_slice::<TranscriptEnvelope>(line) else {
            continue;
        };
        if envelope.kind == "turn_context" && metadata.approvals_reviewer.is_none() {
            metadata.approvals_reviewer = Some(envelope.payload.approvals_reviewer);
        }
        if envelope.kind == "event_msg"
            && envelope.payload.kind.as_deref() == Some("token_count")
            && !found_usage
        {
            found_usage = true;
            metadata.rate_limits = envelope.payload.rate_limits;
            metadata.context_percentage = envelope.payload.info.and_then(|info| {
                let used = info.last_token_usage?.total_tokens;
                let window = info.model_context_window.filter(|window| *window > 0)?;
                Some(((used as f64 / window as f64) * 100.0).clamp(0.0, 100.0) as f32)
            });
        }
        if found_usage && metadata.approvals_reviewer.is_some() {
            break;
        }
    }
    Ok(metadata)
}

fn contains(haystack: &[u8], needle: &[u8]) -> bool {
    haystack
        .windows(needle.len())
        .any(|window| window == needle)
}

fn latest_approvals_reviewer(path: &Path) -> Result<Option<Option<CodexApprovalsReviewer>>> {
    let file = File::open(path)?;
    let length = file.metadata()?.len();
    let mut reader = BufReader::new(file.take(length));
    let mut line = Vec::new();
    let mut reviewer = None;
    while reader.read_until(b'\n', &mut line)? > 0 {
        if line.last() == Some(&b'\n') && contains(&line, br#""type":"turn_context""#) {
            // Typed fields only: ignore instructions, tool arguments, and text.
            if let Ok(envelope) = serde_json::from_slice::<TranscriptEnvelope>(&line) {
                if envelope.kind == "turn_context" {
                    reviewer = Some(envelope.payload.approvals_reviewer);
                }
            }
        }
        line.clear();
    }
    Ok(reviewer)
}

fn codex_process_ids() -> (i32, i32) {
    let own = Pid::from_u32(std::process::id());
    let mut system = System::new();
    system.refresh_processes(ProcessesToUpdate::All, true);
    let mut current = own;
    for _ in 0..10 {
        let Some(process) = system.process(current) else {
            break;
        };
        let Some(parent) = process.parent() else {
            break;
        };
        if let Some(parent_process) = system.process(parent) {
            let name = parent_process.name().to_string_lossy().to_ascii_lowercase();
            let executable = parent_process
                .exe()
                .map(|path| path.to_string_lossy().to_ascii_lowercase())
                .unwrap_or_default();
            if (name.contains("codex") || executable.contains("codex"))
                && !name.contains("agentsmon")
                && !executable.contains("agentsmon")
            {
                return (
                    parent.as_u32() as i32,
                    parent_process.parent().unwrap_or(current).as_u32() as i32,
                );
            }
        }
        current = parent;
    }
    (0, 0)
}

